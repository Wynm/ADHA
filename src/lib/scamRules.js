/**
 * تحليل نص → { score 0..100, hits[], negatives[], verdict }
 * score عالٍ = خطر مرتفع.
 */
export function scan(text) {
  const src = (text || '').trim();
  if (src.length < 8) {
    return { empty: true, score: 0, hits: [], credits: [], verdict: null };
  }
  const hits = [];
  const credits = [];

  for (const rule of RULES) {
    const matched = rule.patterns.filter((p) => p.test(src));
    if (matched.length) {
      hits.push({ ...rule, matches: matched.length });
    }
  }
  for (const n of NEGATIVES) {
    if (n.patterns.some((p) => p.test(src))) credits.push(n);
  }

  const raw =
    hits.reduce((s, h) => s + h.weight * Math.min(1.5, 0.75 + h.matches * 0.25), 0) +
    credits.reduce((s, c) => s + c.weight, 0);

  const score = Math.max(0, Math.min(100, Math.round(raw)));
  return { score, hits, credits, verdict: verdictFor(score), empty: false };
}

