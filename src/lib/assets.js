/**
 * يحسب درجة الخزانة والثغرة الأولى.
 */
export function scoreAssets(levels) {
  let earned = 0;
  const total = ASSETS.reduce((s, a) => s + a.weight, 0);
  const gaps = [];

  for (const a of ASSETS) {
    const v = levels[a.id] ?? 0;
    const contribution = (v / 3) * a.weight;
    earned += contribution;
    if (v < 3) gaps.push({ ...a, v, deficit: a.weight * (1 - v / 3) });
  }

  const pct = Math.round((earned / total) * 100);
  gaps.sort((a, b) => b.deficit - a.deficit);

  return {
    pct,
    earned: Math.round(earned),
    total,
    gaps,
    top: gaps[0] || null,
    strongest: [...ASSETS].sort((a, b) => (levels[b.id] ?? 0) - (levels[a.id] ?? 0))[0],
  };
}

