export function evaluate(answers) {
  let score = 0;
  const gaps = [];
  for (const f of FACTORS) {
    const a = answers[f.id];
    if (a === undefined) continue;
    const opt = f.options.find((o) => o.k === a);
    if (!opt) continue;
    const contribution = opt.v * f.weight;
    score += contribution;
    if (opt.v < 0.5) gaps.push({ ...f, v: opt.v, ar: opt.ar });
  }
  const complete = FACTORS.every((f) => answers[f.id] !== undefined);
  const total = FACTORS.reduce((s, f) => s + f.weight, 0);
  const pct = Math.round((score / total) * 100);
  const mode = FAILURE_MODES.find((m) => pct >= m.min && pct <= m.max) || FAILURE_MODES[0];
  gaps.sort((a, b) => a.v - b.v);
  return { pct, mode, gaps, complete };
}
